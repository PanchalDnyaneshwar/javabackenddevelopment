public class DataTypes {

    public static void main(String[] args) {

        int age = 18;                 // Integer data type
        float marks = 12.45f;         // Decimal value (float needs 'f')
        String name = "Dnyaneshwar";  // String for text

        System.out.println(age);
        System.out.println(marks);
        System.out.println(name);
    }
}

/*
    Data Types in Java:
- Data type defines what kind of data a variable can store.

int:
- Used to store whole numbers.
- Example: age = 18

float:
- Used to store decimal values.
- 'f' is mandatory to tell Java it is a float value.

String:
- Used to store text or characters.
- String is a class, not a primitive data type.

System.out.println():
- Used to print output on the console.


*/